// Builds the deployable site from scripts/atlas-source.html and knowledge/*.md
// Run with: node scripts/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = fs.readFileSync(path.join(root, 'scripts/atlas-source.html'), 'utf8');

// 1. Website: wrap the page in a full HTML document
const head = '<!doctype html><html lang="en"><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">' +
  '<meta name="description" content="Boulder Budget Atlas maps the 2027 budgets of every agency and nonprofit working on homelessness in Boulder County and shows where one budget undercuts or duplicates another, with an AI assistant that answers from public sources.">' +
  '<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>' +
  '</head><body>';
fs.mkdirSync(path.join(root, 'site'), { recursive: true });
fs.writeFileSync(path.join(root, 'site/index.html'), head + src + '</body></html>');

// 2. Assistant knowledge: atlas data + source notes, bundled into the server function
const start = src.indexOf('const CATS=[');
const end = src.indexOf('const E=Object.fromEntries');
const ctx = {};
vm.runInNewContext(src.slice(start, end) + ';__out={CATS,ENTS,ITEMS,LINKS,SRC,EVID,RISK,GOV,OVERSIGHT,ANEC};', ctx);
const { CATS, ENTS, ITEMS, LINKS, SRC, EVID, RISK, GOV, OVERSIGHT, ANEC } = ctx.__out;
const catName = Object.fromEntries(CATS.map(c => [c.id, c.name]));
const url = k => (SRC[k] ? SRC[k].url : null);
const atlas = {
  note: 'Dollar figures are real, in US dollars, each labeled with its year and basis; null means not published. Never add figures from different years or sources. Issues are unconfirmed unless basis is "documented". Board overlaps are not evidence of wrongdoing.',
  entities: ENTS.map(e => ({ id: e.id, name: e.name, type: e.jur, description: e.desc, total_budget_usd: e.dept, total_budget_basis: e.deptLab || null, source: url(e.deptSrc), decision_makers: GOV[e.id] || [] })),
  line_items: ITEMS.map(i => ({ id: i.id, entity: i.e, name: i.name, category: catName[i.cat], amount_usd: i.amt, amount_basis: i.lab, notes: i.note, source: url(i.src) })),
  issues: LINKS.map(l => { const k = l.a + '|' + l.b, r = RISK[k] || {}, o = OVERSIGHT[k] || {}; const type = r.type || l.type; return ({ type: type === 'cannibal' ? 'Cannibalizing' : 'Redundant', basis: l.basis, confidence: l.conf, between: [l.a, l.b], program_undercut: r.v ? (r.v === 'a' ? l.a : l.b) : null, title: l.title, summary: l.summary, mechanism: l.why, harm_to_first: l.hurtA, harm_to_second: l.hurtB, others_affected: l.third, budget_at_risk_usd: r.amt == null ? null : r.amt, budget_at_risk_basis: r.lab || null, oversight: (o.who || []).map(w => w.role + ': ' + w.who), accountability_gap: o.gap || null, documented_concerns: (o.docs || []).map(d => ({ concern: d.t, source: url(d.s) })), from_the_record: (ANEC[k] || []).map(a => ({ account: a.t, who: a.who, where: a.where, date: a.date, counterpoint: !!a.cp, source: a.url })), coordination_options: l.fix, evidence_needed: l.confirm, evidence: (EVID[k] || []).map(url) }); })
};
const kdir = path.join(root, 'knowledge');
const notes = fs.readdirSync(kdir).filter(f => f.endsWith('.md')).sort()
  .map(f => fs.readFileSync(path.join(kdir, f), 'utf8')).join('\n\n');
fs.mkdirSync(path.join(root, 'netlify/lib'), { recursive: true });
fs.writeFileSync(path.join(root, 'netlify/lib/knowledge.mjs'),
  '// Generated by scripts/build.mjs. Do not edit by hand.\n' +
  'export const ATLAS = ' + JSON.stringify(atlas) + ';\n' +
  'export const NOTES = ' + JSON.stringify(notes) + ';\n');
console.log(`Built site/index.html and knowledge (${ENTS.length} entities, ${ITEMS.length} line items, ${LINKS.length} issues, ${Math.round(notes.length / 1000)}k chars of notes).`);
